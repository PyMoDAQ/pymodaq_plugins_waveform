"""Waveform factory: describe a signal by its parameters, get the samples for a given sample rate

A waveform is a dataclass whose fields are its parameters. The same description serves a device that computes the
signal itself from parameters and one that needs the samples (:meth:`Waveform.to_samples`). Fields with a ``unit`` are
numbers expressed in that unit (SI: V, s, Hz, degrees for a phase); a pint quantity is accepted when creating the
waveform and converted.

:class:`WaveformFactory` gives the forms by name (a registry in the spirit of the PyMoDAQ factories, but self contained),
so an application can offer them in a list (``WaveformFactory.names()``) and create one (``WaveformFactory().get('sine',
frequency=1e3)``), and a plugin package can add its own::

    @WaveformFactory.register()
    @dataclasses.dataclass
    class Gaussian(Waveform):
        name: ClassVar[str] = 'gaussian'
        center: float = waveform_field(1e-3, 's', 'Center')
        width: float = waveform_field(1e-4, 's', 'Width')
        duration: float = waveform_field(2e-3, 's', 'Duration')

        def _to_samples(self, sample_rate):
            t = np.arange(self.n_samples(sample_rate)) / sample_rate
            return np.exp(-((t - self.center) / self.width) ** 2 / 2), None

The contract with the applications and the plugins is :data:`WAVEFORM_VERSION`; evolution rule: only add forms and
optional fields, never rename or remove one; a breaking change increments :data:`WAVEFORM_VERSION`.

The forms are in the ``waveforms`` folder, one module each, which register themselves in the factory when imported
(the ``__init__`` of the folder imports them all).
"""
import dataclasses
from abc import ABC, abstractmethod
from typing import Any, ClassVar, Optional, Type, Union

import numpy as np

from pymodaq_data import Q_

WAVEFORM_VERSION = 1


def waveform_field(default: Any, unit: Optional[str] = None, title: str = '', min: Optional[float] = None,
                   max: Optional[float] = None, tip: str = '', type: Optional[str] = None,
                   limits: Optional[list] = None, scannable: Optional[bool] = None) -> Any:
    """A dataclass field that is a parameter of the waveform

    Parameters
    ----------
    default: the default value
    unit: the unit of the number (pint syntax), None for a parameter that is not a physical quantity (see ``type``)
    title: the label of the parameter in the settings
    min, max: bounds of the parameter in the settings (and checked when the samples are computed)
    tip: help shown on the parameter
    type: the type of the parameter in the settings: ``'float'`` (the default when there is a ``unit``), ``'str'`` (the
        default without unit), ``'int'``, ``'bool'`` or ``'list'`` (a choice among ``limits``)
    limits: the choices of a ``'list'`` parameter
    scannable: True if a scan can drive this parameter. By default only the numbers (``'float'`` and ``'int'``) are,
        not the choices, flags and texts
    """
    if unit is not None and type not in (None, 'float'):
        raise ValueError(f'A parameter with a unit is a float, not {type}')
    type = 'float' if unit is not None else (type or 'str')
    if scannable is None:
        scannable = type in ('float', 'int')
    if scannable and type not in ('float', 'int'):
        raise ValueError(f'A {type} parameter cannot be scanned')
    if type not in ('float', 'str', 'int', 'bool', 'list'):
        raise ValueError(f'Unknown parameter type {type}')
    if type == 'list' and not limits:
        raise ValueError('A list parameter needs its limits')
    return dataclasses.field(default=default, metadata=dict(unit=unit, title=title, min=min, max=max, tip=tip,
                                                            type=type, limits=limits, scannable=scannable))


@dataclasses.dataclass(frozen=True)
class SampledWaveform:
    """The samples of a waveform for one sample rate

    Attributes
    ----------
    samples: the signal, in volts for a voltage output. One period for a periodic waveform (to be repeated), the whole
        signal otherwise
    sample_rate: Hz
    periodic: True if ``samples`` is one period to repeat
    frequency: Hz, the frequency that is really generated by repeating ``samples`` (periodic waveform only). It is the
        requested one rounded so that a period has a whole number of samples
    frequency_error: Hz, ``frequency`` minus the requested frequency
    """
    samples: np.ndarray
    sample_rate: float
    periodic: bool = False
    frequency: Optional[float] = None
    frequency_error: float = 0.

    @property
    def duration(self) -> float:
        """Seconds"""
        return len(self.samples) / self.sample_rate


class Waveform(ABC):
    """Base class of the waveforms. Subclass it with a dataclass, set ``name`` and register it"""
    name: ClassVar[str] = ''
    periodic: ClassVar[bool] = False  # True: :meth:`to_samples` gives one period to repeat

    def __post_init__(self):
        """Called by the ``__init__`` that the dataclass decorator of each form generates, once the fields are set"""
        self._validate_parameters()

    def _validate_parameters(self) -> None:
        """Check and normalize the value of every parameter (the fields declared with :func:`waveform_field`)

        For each parameter, according to its type:

        - ``float``: a pint quantity is converted to the unit of the field, any number is made a ``float``;
        - ``int`` and ``bool``: the value is converted to this type;
        - ``list``: the value should be one of the ``limits`` of the field;
        - ``float`` and ``int``: the value should be within ``min`` and ``max`` if they are set.

        The converted value replaces the given one. A ``ValueError`` names the waveform and the parameter when a bound
        or a choice is not respected. A form with more to check extends :meth:`__post_init__` and calls ``super()``.
        """
        for field in self._parameters():
            value = getattr(self, field.name)
            meta = field.metadata
            unit, type_ = meta['unit'], meta['type']
            if type_ == 'float':
                value = float(value.m_as(unit)) if isinstance(value, Q_) else float(value)
            elif type_ == 'int':
                value = int(value)
            elif type_ == 'bool':
                value = bool(value)
            elif type_ == 'list' and value not in meta['limits']:
                raise ValueError(f'{self.name}: {field.name} = {value} is not one of {meta["limits"]}')
            if type_ in ('float', 'int'):
                lower, upper = meta['min'], meta['max']
                if (lower is not None and value < lower) or (upper is not None and value > upper):
                    raise ValueError(f'{self.name}: {field.name} = {value} {unit or ""} is out of its limits '
                                     f'({lower}, {upper})')
            setattr(self, field.name, value)

    # ---- the description as settings
    @classmethod
    def _parameters(cls) -> list[dataclasses.Field]:
        return [field for field in dataclasses.fields(cls) if 'unit' in field.metadata]

    @classmethod
    def scannable_parameters(cls) -> list[str]:
        """Names of the parameters that a scan can drive (the numbers, unless a field says otherwise)"""
        return [field.name for field in cls._parameters() if field.metadata['scannable']]

    def to_dict(self) -> dict:
        """The waveform as a dictionary (its ``name`` and its parameters), to be saved and read by :meth:`from_dict`"""
        return {'name': self.name, **{field.name: getattr(self, field.name) for field in self._parameters()}}

    @classmethod
    def from_dict(cls, description: dict) -> 'Waveform':
        """Build the waveform of a dictionary made by :meth:`to_dict`; the class is found by its ``name``"""
        parameters = dict(description)
        return WaveformFactory.create(parameters.pop('name'), **parameters)

    @classmethod
    def params(cls) -> list[dict]:
        """The parameters of this waveform as a list of settings dictionaries (pyqtgraph Parameter syntax)"""
        params = []
        for field in cls._parameters():
            meta = field.metadata
            param = {'title': meta['title'] or field.name, 'name': field.name, 'value': field.default,
                     'tip': meta['tip']}
            param['type'] = meta['type']
            if meta['type'] == 'list':
                param['limits'] = list(meta['limits'])
            elif meta['type'] == 'int':
                for key in ('min', 'max'):
                    if meta[key] is not None:
                        param[key] = meta[key]
            elif meta['type'] == 'float':
                dimensionless = meta['unit'] in ('dimensionless', 'deg')  # no SI prefix (k, m) in front of these
                param.update(suffix='' if meta['unit'] == 'dimensionless' else meta['unit'],
                             siPrefix=not dimensionless)
                for key in ('min', 'max'):
                    if meta[key] is not None:
                        param[key] = meta[key]
            params.append(param)
        return params

    @classmethod
    def from_settings(cls, group) -> 'Waveform':
        """Build the waveform from a settings group (a Parameter) holding the children of :meth:`params`"""
        return cls(**{field.name: group[field.name] for field in cls._parameters()})

    # ---- the samples
    def n_samples(self, sample_rate: float) -> int:
        """Number of samples of a waveform defined by its ``duration`` (at least 2)"""
        return max(2, int(round(getattr(self, 'duration') * sample_rate)))

    @abstractmethod
    def _to_samples(self, sample_rate: float) -> tuple[np.ndarray, Optional[float]]:
        """The samples and, for a periodic waveform, the frequency really generated"""

    def to_samples(self, sample_rate: Union[float, Q_]) -> SampledWaveform:
        """The samples of the waveform for ``sample_rate`` (Hz, or a pint quantity)"""
        sample_rate = float(sample_rate.m_as('Hz')) if isinstance(sample_rate, Q_) else float(sample_rate)
        if sample_rate <= 0:
            raise ValueError('The sample rate should be positive')
        samples, frequency = self._to_samples(sample_rate)
        requested = getattr(self, 'frequency', None)
        return SampledWaveform(np.asarray(samples, dtype=float), sample_rate, self.periodic, frequency,
                                0. if frequency is None else frequency - requested)


class WaveformFactory:
    """Registry of the waveforms by name, and their creation

    ``@WaveformFactory.register()`` on a :class:`Waveform` dataclass registers it under its ``name`` (a class attribute,
    the only place where the name is written, as ``elt_name`` of the sequencer elements). The
    registry belongs to the class, so there is a single one whatever the number of instances.
    """
    _waveforms: dict[str, Type[Waveform]] = {}

    @classmethod
    def register(cls):
        """Class decorator registering a waveform under its ``name``"""
        def inner_wrapper(wrapped_class: Type[Waveform]) -> Type[Waveform]:
            if not wrapped_class.name:
                raise ValueError(f'{wrapped_class.__name__} has no name: set the class attribute ``name``')
            cls._waveforms[wrapped_class.name] = wrapped_class
            return wrapped_class
        return inner_wrapper

    @classmethod
    def unregister(cls, key: str) -> None:
        cls._waveforms.pop(key, None)

    @classmethod
    def names(cls) -> list[str]:
        """Names of the registered waveforms, sorted as the form modules are imported"""
        return list(cls._waveforms)

    @classmethod
    def get_class(cls, key: str) -> Type[Waveform]:
        try:
            return cls._waveforms[key]
        except KeyError:
            raise KeyError(f'Unknown waveform {key}, available: {cls.names()}') from None

    @classmethod
    def create(cls, name: str, **parameters) -> Waveform:
        """Create the waveform registered as ``name`` from its parameters (numbers or pint quantities)"""
        return cls.get_class(name)(**parameters)

    def get(self, name: str, **parameters) -> Waveform:
        """Same as :meth:`create`"""
        return self.create(name, **parameters)
